-- منصة الحديث الشريف — إصلاحات أمنية مشتقة من مراجعة 19-security-model.md
-- Version: 1.0 | 2026-08-06
--
-- ثلاث ثغرات كُشفت بمراجعة الكود مقابل السياسات، لا بالقراءة النظرية:
--   [SEC-01 P1] ALG-005 (حد الرفع) مطبَّق في الواجهة فقط. أي استدعاء مباشر
--               للـAPI يتجاوزه ⇒ استنزاف التخزين وحصة Egress.
--   [SEC-02 P0] استبدال التسجيل معطَّل في الوضع الحيّ: الكود يستعمل upsert،
--               وPostgres ينفّذه UPDATE عند التعارض، والطالب لا يملك سياسة
--               UPDATE ⇒ ALG-004 لا تعمل إطلاقاً.
--   [SEC-04 P2] لا أثر تدقيق لأفعال المشرف الحساسة.
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- SEC-01 — فرض حدّ الرفع في قاعدة البيانات لا في المتصفح
-- -----------------------------------------------------------------------------
-- نحسب على updated_at لا created_at، فالاستبدال يجب أن يُحتسب أيضاً وإلا
-- استطاع الطالب استبدال نفس التسجيل ألف مرة دون أن يمسّه الحدّ.
CREATE OR REPLACE FUNCTION upload_rate_ok()
RETURNS BOOLEAN AS $$
    SELECT (
        SELECT count(*) FROM public.recordings
        WHERE user_id = auth.uid()
          AND updated_at > now() - interval '1 hour'
    ) < public.get_setting_int('rate_limit_uploads_per_hour', 5);
$$ LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public;

DROP POLICY IF EXISTS recordings_insert_student ON recordings;
CREATE POLICY recordings_insert_student ON recordings
    FOR INSERT TO authenticated WITH CHECK (
        auth.uid() = user_id
        AND has_upload_consent()
        AND get_setting_bool('upload_enabled', true) = true
        AND upload_rate_ok()                          -- [FIX SEC-01]
    );

-- -----------------------------------------------------------------------------
-- SEC-02 — تمكين الاستبدال مع حماية الحقول الإشرافية
-- -----------------------------------------------------------------------------
-- RLS لا تستطيع تقييد الأعمدة، فنمنح الطالب UPDATE على صفّه ثم نُجمّد
-- الحقول الحسّاسة بمشغّل. النتيجة: يستبدل ملفه ومدّته فقط.
CREATE OR REPLACE FUNCTION guard_recording_update()
RETURNS TRIGGER AS $$
BEGIN
    IF is_admin() THEN RETURN NEW; END IF;

    NEW.user_id       := OLD.user_id;
    NEW.hadith_id     := OLD.hadith_id;
    NEW.is_verified   := OLD.is_verified;
    NEW.verified_by   := OLD.verified_by;
    NEW.verified_at   := OLD.verified_at;
    NEW.is_hidden     := OLD.is_hidden;
    NEW.hidden_reason := OLD.hidden_reason;
    NEW.likes_count   := OLD.likes_count;      -- تُصان بالمشغّلات وحدها
    NEW.listens_count := OLD.listens_count;
    NEW.created_at    := OLD.created_at;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

DROP TRIGGER IF EXISTS trg_guard_recording_update ON recordings;
CREATE TRIGGER trg_guard_recording_update
    BEFORE UPDATE ON recordings
    FOR EACH ROW EXECUTE FUNCTION guard_recording_update();

DROP POLICY IF EXISTS recordings_update_own ON recordings;
CREATE POLICY recordings_update_own ON recordings
    FOR UPDATE TO authenticated
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id AND upload_rate_ok());   -- الحدّ يشمل الاستبدال

-- -----------------------------------------------------------------------------
-- SEC-04 — أثر تدقيق لأفعال المشرف
-- -----------------------------------------------------------------------------
-- بلا هذا، حذف المشرف لتسجيل طالب لا يترك أثراً — وهذه منصة يرفع فيها
-- الطلاب عملهم، فالمساءلة جزء من الثقة لا ترف.
CREATE TABLE IF NOT EXISTS audit_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id   UUID REFERENCES profiles(id) ON DELETE SET NULL,
    action     TEXT NOT NULL,
    table_name TEXT NOT NULL,
    row_id     TEXT,
    details    JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_log (created_at DESC);

ALTER TABLE audit_log ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS audit_select_admin ON audit_log;
CREATE POLICY audit_select_admin ON audit_log
    FOR SELECT TO authenticated USING ((SELECT is_admin()));
-- لا سياسة INSERT/UPDATE/DELETE: يُكتب بمشغّلات SECURITY DEFINER فقط،
-- فلا يستطيع أحد — ولا المشرف — تزوير الأثر أو محوه من الواجهة.

CREATE OR REPLACE FUNCTION log_recording_admin_action()
RETURNS TRIGGER AS $$
BEGIN
    IF NOT is_admin() THEN RETURN COALESCE(NEW, OLD); END IF;

    IF TG_OP = 'DELETE' THEN
        INSERT INTO audit_log (actor_id, action, table_name, row_id, details)
        VALUES (auth.uid(), 'delete', 'recordings', OLD.id::text,
                jsonb_build_object('owner', OLD.user_id, 'hadith', OLD.hadith_id));
        RETURN OLD;
    END IF;

    IF OLD.is_verified IS DISTINCT FROM NEW.is_verified
       OR OLD.is_hidden IS DISTINCT FROM NEW.is_hidden THEN
        INSERT INTO audit_log (actor_id, action, table_name, row_id, details)
        VALUES (auth.uid(), 'moderate', 'recordings', NEW.id::text,
                jsonb_build_object('verified', NEW.is_verified, 'hidden', NEW.is_hidden));
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

DROP TRIGGER IF EXISTS trg_audit_recordings ON recordings;
CREATE TRIGGER trg_audit_recordings
    AFTER UPDATE OR DELETE ON recordings
    FOR EACH ROW EXECUTE FUNCTION log_recording_admin_action();

COMMIT;

SELECT 'security fixes applied' AS done;
